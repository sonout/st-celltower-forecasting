import pandas as pd
import numpy as np
import yaml
import json
import pickle
import warnings
import random
import platform
from importlib.metadata import version
import torch
from pathlib import Path
from typing import Dict, List, Any
from datetime import datetime
from uuid import uuid4

from .utils import calculate_metrics
from .datasets import resolve_dataset, verify_manifest, file_sha256
from .configuration import PROJECT_ROOT, MODEL_CONFIG_DIR

# Model imports using the registry pattern
from models.graph_wavenet import GraphWaveNetModel
from models.sequence_baselines import (
    HistoricalPatternModel, SeasonalNaiveModel, RandomForestModel, ARIMAModel, XGBoostModel,
)

MODEL_REGISTRY = {
    'graph_wavenet': GraphWaveNetModel,
    'historical_average': HistoricalPatternModel,
    'historical': HistoricalPatternModel,
    'ha': HistoricalPatternModel, # Alias for historical average
    'seasonal_naive': SeasonalNaiveModel,
    'gwn': GraphWaveNetModel,
    'random_forest': RandomForestModel,
    'arima': ARIMAModel,
    'xgboost': XGBoostModel,
}

class TelecomPipeline:
    """
    Main pipeline for telecom KPI prediction experiments.
    This version is adapted to load pre-sequenced NumPy data,
    which significantly speeds up the experimentation loop by separating
    heavy data processing from model training and evaluation.
    """

    def __init__(self, config: Dict[str, Any]):
        """
        Initializes the pipeline with the experiment configuration.

        Args:
            config: Configuration dictionary from an experiment YAML.
        """
        self.config = config
        self.models = {}
        self.results = {}
        self.metadata = {}
        self.model_configs = {}
        self.timestamps = {}
        self.run_id = datetime.now().strftime('%Y%m%d_%H%M%S') + '-' + uuid4().hex[:8]

        # Placeholders for the preprocessed sequence data
        self.X_train, self.Y_train = None, None
        self.X_val, self.Y_val = None, None
        self.X_test, self.Y_test = None, None
        self.static_features = None

    def _load_data(self):
        """
        Loads the pre-split and sequenced NumPy arrays and metadata
        generated by the preprocessing.py script.
        """
        data_dir = resolve_dataset(self.config['data']['output_dir'], self.config['data'].get('dataset_id'))
        self.dataset_dir = data_dir.resolve()
        self.dataset_manifest = verify_manifest(data_dir)
        print(f"Loading preprocessed sequence data from: {data_dir}")

        # Load metadata first to have context
        metadata_path = data_dir / 'metadata.yaml'
        if not metadata_path.exists():
            raise FileNotFoundError(f"Metadata file not found at {metadata_path}. Please run the preprocessing script first.")
        with open(metadata_path, 'r') as f:
            self.metadata = yaml.safe_load(f)
        if not self.dataset_manifest:
            self.dataset_manifest = {
                'dataset_id': 'legacy-' + file_sha256(metadata_path)[:12],
                'sha256': {p.name: file_sha256(p) for p in sorted(data_dir.iterdir())
                           if p.name == 'metadata.yaml' or p.name.startswith(('X_', 'Y_', 'timestamps_'))},
            }
        if self.metadata.get('schema_version', 1) < 2:
            if not self.config['experiment'].get('allow_legacy_data', False):
                raise ValueError('Legacy data has overlapping split targets. Regenerate it with python -m src.preprocessing, or use --allow-legacy-data for diagnostics.')
            warnings.warn('Using legacy data with possible split overlap; metrics are diagnostic only.')
        for key in ('input_steps', 'output_steps', 'granularity_min'):
            if self.metadata[key] != self.config['data'][key]:
                raise ValueError(f'Dataset {key} differs from config; rerun preprocessing.')
        if self.metadata['target_columns'] != self.config['target_kpis']:
            raise ValueError('Dataset target KPIs differ from config; rerun preprocessing.')
        expected_features = self.config['data']['kpi_columns']
        if self.metadata['feature_columns'][:len(expected_features)] != expected_features:
            raise ValueError('Dataset input KPIs differ from config; rerun preprocessing.')
        original = self.metadata.get('preprocessing_config', {})
        for key in ('add_timefeats', 'cyclic_timefeats', 'lag_hours', 'rolling_avg_hours'):
            if original and original.get(key) != self.config['data'].get(key):
                raise ValueError(f'Dataset feature setting {key} differs from config; rerun preprocessing.')
        if self.metadata.get('schema_version', 1) >= 2 and self.metadata.get('data_split') != self.config.get('data_split'):
            raise ValueError('Dataset date split differs from config; rerun preprocessing.')

        # Load all NumPy array splits
        try:
            limit = self.config['experiment'].get('sample_limit')
            for split in ('train', 'val', 'test'):
                for kind in ('X', 'Y'):
                    array = np.load(data_dir / f'{kind}_{split}.npy', mmap_mode='r')
                    if limit:
                        array = np.array(array[:limit])
                    setattr(self, f'{kind}_{split}', array)
                with open(data_dir / f'timestamps_{split}.pkl', 'rb') as stream:
                    stamps = pickle.load(stream)
                self.timestamps[split] = stamps[:limit] if limit else stamps
                x, y = getattr(self, f'X_{split}'), getattr(self, f'Y_{split}')
                if len(x) != len(y) or len(x) != len(self.timestamps[split]) or not len(x):
                    raise ValueError(f'Invalid {split} sample counts.')
                expected_x = (self.metadata['input_steps'], self.metadata['n_cells'], self.metadata['n_features'])
                expected_y = (self.metadata['output_steps'], self.metadata['n_cells'], self.metadata['n_targets'])
                if x.shape[1:] != expected_x or y.shape[1:] != expected_y:
                    raise ValueError(f'Invalid {split} array dimensions.')
                if not np.isfinite(x).all() or not np.isfinite(y).all():
                    raise ValueError(f'Nonfinite values in {split} arrays.')
        except FileNotFoundError as e:
            print(f"Error loading sequence data: {e}")
            print("Please ensure the preprocessing script has been run successfully.")
            raise

        # Load static features if they exist
        static_features_path = data_dir / 'static_features.npy'
        if static_features_path.exists():
            self.static_features = np.load(static_features_path, allow_pickle=True)
            print(f"  ... Loaded static features with shape: {self.static_features.shape}")

        print("\n✅ Data Loading Complete:")
        print(f"  Train shapes: X={self.X_train.shape}, Y={self.Y_train.shape}")
        print(f"  Val shapes:   X={self.X_val.shape}, Y={self.Y_val.shape}")
        print(f"  Test shapes:  X={self.X_test.shape}, Y={self.Y_test.shape}")
        print(f"  Metadata loaded for {self.metadata.get('n_cells', 'N/A')} cells and {self.metadata.get('n_features', 'N/A')} features.")

    def _store_predictions(self, model_name: str, predictions: np.ndarray) -> None:
        """
        Stores model predictions to disk if configured.
        
        Args:
            model_name: Name of the model
            predictions: Predictions array (n_sequences, output_steps, n_cells, n_targets)
        """
        preprocessing_output_dir = self.dataset_dir
        store_dir = Path(self.config['experiment'].get('store_predictions_folder', 'predictions'))
        store_dir.mkdir(parents=True, exist_ok=True)
        
        timestamp = self.run_id
        kpis_str = '_'.join(self.config['target_kpis']) # Still useful for a descriptive filename
        filename = f"{model_name}_{kpis_str}_{timestamp}"
        pred_path = store_dir / f"{filename}.npz"

        # Snapshot the dataset identity and settings used by this run.
        pred_metadata = {
            'model_name': model_name,
            'prediction_timestamp': timestamp,
            # This is the critical link back to the dataset version that was used.
            'preprocessing_metadata_path': str(preprocessing_output_dir / 'metadata.yaml'),
            'dataset_metadata': self.metadata,
            'dataset_manifest': self.dataset_manifest,
            'model_config': self.model_configs[model_name],
            'sample_limit': self.config['experiment'].get('sample_limit'),
        }

        np.savez_compressed(
            pred_path,
            predictions=predictions,
            metadata=json.dumps(pred_metadata, indent=4) # indent makes it human-readable if extracted
        )
        
        # The size calculation should be on the saved file, not the in-memory array for accuracy
        file_size_mb = pred_path.stat().st_size / 1024 / 1024
        print(f"💾 Predictions saved to: {pred_path} ({file_size_mb:.2f} MB)")

    def run_experiment(self) -> Dict[str, Any]:
        """
        Runs the complete experiment pipeline:
        1. Loads pre-sequenced data.
        2. Initializes models specified in the config.
        3. Trains each model.
        4. Generates predictions on the test set.
        5. Evaluates predictions and prints results.
        6. Stores and returns the combined results.

        Returns:
            A nested dictionary containing the evaluation metrics for all models.
        """
        print("\n" + "="*80)
        print("🚀 Starting Telecom KPI Prediction Experiment")
        print("="*80)

        seed = self.config['experiment'].get('random_seed', 42)
        torch.set_num_threads(self.config['experiment'].get('cpu_threads', 4))
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
        torch.backends.cudnn.benchmark = False
        torch.use_deterministic_algorithms(True, warn_only=True)

        # 1. Load the pre-processed and sequenced data
        self._load_data()

        # 2. Initialize models
        model_names = self.config['experiment']['models']
        print(f"\nInitializing models: {model_names}")
        self.models = self._load_models(model_names)

        # 3. Get experiment parameters
        target_kpis = self.config['target_kpis']
        horizons = self.config['horizons']

        # 4. Run training and evaluation for each model
        all_results = {}
        for model_name, model in self.models.items():
            print(f"\n{'='*60}")
            print(f"Processing Model: {model_name.upper()}")
            print(f"{'='*60}")

            print(f"Training {model_name}...")
            # The model's train method must be updated to accept these numpy arrays
            model.train(
                X_train=self.X_train, Y_train=self.Y_train,
                X_val=self.X_val, Y_val=self.Y_val,
                static_features=self.static_features
            )

            print("\nPredicting on the test set...")
            # The model's predict method should return a NumPy array of shape:
            # (n_sequences, output_steps, n_cells, n_targets)
            predictions_array = model.predict(
                X_test=self.X_test,
                static_features=self.static_features
            )
            if predictions_array.shape != self.Y_test.shape or not np.isfinite(predictions_array).all():
                raise ValueError(f'{model_name} returned invalid predictions.')
            if self.config['experiment'].get('save_model_checkpoints', False):
                suffix = '.pt' if isinstance(model, GraphWaveNetModel) else '.pkl'
                model.save(Path(self.config['experiment']['output_dir']) / 'checkpoints' / f'{model_name}_{self.run_id}{suffix}')
            
            # Store predictions if configured
            if self.config['experiment'].get('store_predictions', False):
                self._store_predictions(model_name, predictions_array)

            print("\nEvaluating predictions...")
            model_results = self._evaluate_predictions(
                predictions=predictions_array,
                y_true_all=self.Y_test,
                target_kpis=target_kpis,
                horizons=horizons
            )
            all_results[model_name] = model_results

        # 5. Print final comparison and store results
        self._print_summary_comparison(all_results, target_kpis, horizons)
        self.results = all_results
        
        # Save results to disk
        output_dir = Path(self.config['experiment']['output_dir'])
        output_dir.mkdir(parents=True, exist_ok=True)
        self.results_path = output_dir / f"{self.config['experiment']['name']}_{self.run_id}.json"
        self.save_results(self.results_path)

        return all_results

    def _load_models(self, model_names: List[str]) -> Dict[str, Any]:
        """
        Load and initialize models using the MODEL_REGISTRY.
        It passes necessary metadata from preprocessing to each model's constructor.
        """
        models = {}
        for model_name in model_names:
            if model_name not in MODEL_REGISTRY:
                raise ValueError(f"Unknown model type: '{model_name}'. Available models: {list(MODEL_REGISTRY.keys())}")

            print(f"  - Initializing model: {model_name}")
            try:
                config_name = {'gwn': 'graph_wavenet', 'ha': 'historical_average', 'historical': 'historical_average'}.get(model_name, model_name)
                with (MODEL_CONFIG_DIR / f'{config_name}.yaml').open() as f:
                    model_config = yaml.safe_load(f) or {}
            except FileNotFoundError:
                model_config = {}

            # Combine general and model-specific configs, and add crucial metadata
            combined_config = {
                **model_config,
                **self.config['experiment'].get('model_overrides', {}).get(config_name, {}),
                **self.config['experiment'].get('model_overrides', {}).get(model_name, {}),
                'horizons': self.config['horizons'],
                'device': self.config['experiment'].get('device', 'cpu'),
                'input_steps': self.config['data']['input_steps'],
                'output_steps': self.config['data']['output_steps'],
                **self.metadata # Unpack all metadata (n_features, n_targets, etc.)
            }
            combined_config['random_seed'] = self.config['experiment'].get('random_seed', 42)
            if combined_config['device'] == 'auto':
                combined_config['device'] = 'cuda:0' if torch.cuda.is_available() else 'cpu'
            if MODEL_REGISTRY[model_name] is GraphWaveNetModel:
                graph_path = Path(combined_config['graph_path'])
                combined_config['graph_path'] = str(graph_path if graph_path.is_absolute() else PROJECT_ROOT / graph_path)
                combined_config['graph_sha256'] = file_sha256(Path(combined_config['graph_path']))
            self.model_configs[model_name] = dict(combined_config)
            combined_config.update({f'timestamps_{s}': self.timestamps[s] for s in ('train', 'val', 'test')})

            model_class = MODEL_REGISTRY[model_name]
            models[model_name] = model_class(combined_config)

        return models

    def _evaluate_predictions(
        self,
        predictions: np.ndarray,
        y_true_all: np.ndarray,
        target_kpis: List[str],
        horizons: Dict[str, int]
    ) -> Dict[str, Any]:
        """
        Evaluates model predictions against ground truth for all KPIs and horizons.
        This version operates directly on NumPy arrays for high efficiency.

        Args:
            predictions: Predicted values array (n_sequences, output_steps, n_cells, n_targets).
            y_true_all: Ground truth values array (n_sequences, output_steps, n_cells, n_targets).
            target_kpis: A list of the target KPI strings to evaluate.
            horizons: A dictionary mapping horizon names to their step counts.

        Returns:
            A nested dictionary containing the evaluation metrics for the model.
        """
        if predictions.shape != y_true_all.shape:
            raise ValueError('Prediction and target shapes must match.')
        results = {}
        target_columns_ordered = self.metadata['target_columns']

        for kpi in target_kpis:
            try:
                # Find the column index for the current KPI
                kpi_index = target_columns_ordered.index(kpi)
            except ValueError:
                print(f"Warning: Skipping KPI '{kpi}' as it was not found in the model's target columns.")
                continue

            print(f"\n--- Evaluating KPI: {kpi} ---")
            results[kpi] = {}

            for horizon_name, horizon_steps in horizons.items():
                # Get the 0-based index for the horizon (e.g., horizon step 4 -> index 3)
                horizon_idx = horizon_steps - 1
                if horizon_idx >= predictions.shape[1]:
                    raise ValueError(f'Horizon {horizon_name} exceeds the output window.')
                if horizon_steps < 1:
                    raise ValueError('Horizon steps must be positive.')
                
                # Slice arrays to get all values for the specific KPI and horizon.
                # .flatten() creates a 1D array of all predictions/truths for that time step across all sequences and cells.
                y_pred_flat = predictions[:, horizon_idx, :, kpi_index].flatten()
                y_true_flat = y_true_all[:, horizon_idx, :, kpi_index].flatten()

                # Calculate and store metrics
                metrics = calculate_metrics(y_true_flat, y_pred_flat, self.config.get('evaluation', {}).get('metrics'))
                results[kpi][horizon_name] = metrics

                print(f"  {horizon_name:>6s} -> " + ', '.join(f'{name.upper()}: {value:.4f}' for name, value in metrics.items()))
        return results

    def _print_summary_comparison(self, all_results: Dict[str, Any], target_kpis: List[str], horizons: Dict[str, int]) -> None:
        """
        Prints a final summary table comparing the MAE of all models across all horizons for each KPI.
        """
        print("\n" + "="*80)
        print("🏆 Final Model Comparison (Mean Absolute Error - MAE)")
        print("="*80)

        model_names = sorted(all_results.keys())
        horizon_names = list(horizons.keys())

        for kpi in target_kpis:
            print(f"\nKPI: {kpi}")
            # Dynamic width for the table
            header_line = "-" * (23 + 13 * len(horizon_names))
            print(header_line)

            header = f"{'Model':<20} | " + " | ".join(f"{h:>10s}" for h in horizon_names)
            print(header)
            print("-" * len(header))

            # Data rows for each model
            for model_name in model_names:
                mae_values = []
                for horizon in horizon_names:
                    # Use .get() for safe access to avoid errors if a result is missing
                    metrics = all_results.get(model_name, {}).get(kpi, {}).get(horizon)
                    value = metrics.get('mae') if metrics else None
                    mae_values.append(f"{value:10.2f}" if value is not None else "     N/A  ")
                print(f"{model_name:<20} | " + " | ".join(mae_values))

            print("-" * len(header))
            print("Best model per horizon:")
            for horizon in horizon_names:
                best_model, best_mae = None, float('inf')
                for model_name in model_names:
                    metrics = all_results.get(model_name, {}).get(kpi, {}).get(horizon)
                    if metrics and 'mae' in metrics:
                        mae = metrics['mae']
                        if not np.isnan(mae) and mae < best_mae:
                            best_mae, best_model = mae, model_name

                if best_model:
                    print(f"  {horizon:>10s}: {best_model} (MAE: {best_mae:.2f})")
                else:
                    print(f"  {horizon:>10s}: No valid results")
            print("-" * 80)

    def save_results(self, output_path: str) -> None:
        """Saves the final configuration and results to a JSON file."""
        
        def convert_numpy_types(obj):
            """Helper function to convert numpy types to native Python types for JSON serialization."""
            if isinstance(obj, np.integer): return int(obj)
            if isinstance(obj, np.floating): return float(obj)
            if isinstance(obj, np.ndarray): return obj.tolist()
            return obj

        # Use json.dumps with a default converter to handle numpy types
        serializable_results = json.loads(json.dumps(self.results, default=convert_numpy_types))
        
        Path(output_path).parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w') as f:
            json.dump({
                'config': self.config,
                'run_id': self.run_id,
                'runtime': {'python': platform.python_version(), **{
                    package: version(package) for package in (
                        'torch', 'numpy', 'pandas', 'scipy', 'scikit-learn',
                        'statsmodels', 'xgboost', 'networkx')}},
                'model_configs': self.model_configs,
                'dataset_metadata': self.metadata,
                'dataset_manifest': self.dataset_manifest,
                'dataset_path': str(self.dataset_dir),
                'results': serializable_results
            }, f, indent=4)

        print(f"\n✅ Results saved to: {output_path}")
